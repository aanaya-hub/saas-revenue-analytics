def figure_cluster_profiles(profiles):
    """Standardised profile of each cluster, so groups can be compared at a glance.

    The features are on wildly different scales — seats run to hundreds, discount
    between 0 and 0.45 — so raw averages cannot share an axis. Each is therefore
    rescaled to a z-score: how far this cluster sits from the overall average, in
    standard deviations. Zero means typical, +1 means one standard deviation above.
    """
    features = CLUSTER_FEATURES
    matrix = np.array([[profile[feature] for feature in features] for profile in profiles])

    # * ddof=0 because these are the clusters we have, not a sample drawn from a
    # * wider population — there is no wider population to estimate.
    mean = matrix.mean(axis=0)
    std = matrix.std(axis=0)
    # * Guard against a zero standard deviation, which would divide by zero if a
    # * feature happened to be constant across the clusters.
    std = np.where(std == 0, 1.0, std)
    standardised = (matrix - mean) / std

    fig, ax = plt.subplots(figsize=(12, 6.5))
    colours = config.PALETTE[:len(profiles)]
    for row, profile, colour in zip(standardised, profiles, colours):
        ax.plot(features, row, marker="o", linewidth=2.4, color=colour,
                label=f"cluster {profile['cluster']} (n={profile['customers']}, "
                      f"churn {profile['churn_rate']:.0%})")

    ax.axhline(0, color="#999999", linestyle="--", linewidth=1.4)
    ax.set_ylabel("Standard deviations from the overall average")
    ax.set_title("What each cluster actually looks like", fontsize=13, fontweight="bold")
    ax.legend(frameon=False, loc="best")
    plt.setp(ax.get_xticklabels(), rotation=25, ha="right")
    return _save(fig, "21-cluster-profiles.png")


