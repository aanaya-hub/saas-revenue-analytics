# 3. RECONCILE — does the invoice arithmetic hold?
# ============================================================================

def reconcile_invoices(df):
    """Check that mrr equals seats x list price x (1 - discount).

    WHY THIS CHECK EXISTS
    It is the one relationship in the data with an exact expected answer. If the
    recorded MRR disagrees with the arithmetic, then either the price list or the
    revenue figure is wrong — and every revenue conclusion drawn afterwards is
    built on sand.

    Real finance teams reconcile like this every month. It is also the single
    most convincing thing to show an interviewer, because it demonstrates that
    the numbers were checked rather than trusted.
    """
    expected = df["seats"] * df["list_price_per_seat"] * (1.0 - df["discount_pct"])
    difference = (df["mrr"] - expected).abs()

    # ! THE TOLERANCE HAS TO MATCH HOW THE DATA WAS MADE.
    # ! The generator multiplies every invoice by a deliberate 3% wobble
    # ! (config.MRR_NOISE_SD), imitating real billing variance. Checking for a
    # ! 1% match therefore FAILS on about three quarters of perfectly good rows:
    # ! the first run of this function reported a 27% match rate and looked like
    # ! a serious data problem, when the check itself was simply too strict.
    # ! A 5% band is the right question to ask of 3%-noisy data.
    percent_difference = (difference / expected.abs().clip(lower=1.0)) * 100
    within_5 = percent_difference <= 5.0

    return {
        "rows_checked": int(len(df)),
        "within_5_percent": int(within_5.sum()),
        "mismatched": int((~within_5).sum()),
        "match_rate": round(float(within_5.mean()), 4),
        "median_percent_difference": round(float(percent_difference.median()), 4),
        "mean_absolute_difference": round(float(difference.mean()), 4),
        "tolerance_note": "Generator applies 3% invoice noise, so 5% is the correct tolerance",
    }


