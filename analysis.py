# 1. LOAD — read the star schema back through SQL
# ============================================================================

# * One query pulling the whole star schema together. Written out as a constant
# * rather than built with string concatenation, because a visible query can be
# * read, checked and pasted into a SQL client; a generated one cannot.
# *
# * Reading it top to bottom:
# *   FROM fact_subscription_monthly f   the central table; `f` is its alias
# *   JOIN dim_customer  c ON ...        attach the customer behind each row
# *   JOIN dim_plan      p ON ...        attach the plan, to get the list price
# *   JOIN dim_region    r ON ...        attach the region
# *   JOIN dim_date      d ON ...        attach the month label
# *
# * The customer→region join is a LEFT JOIN on purpose. Three customers have a
# * blank region_id (a deliberate defect). An INNER JOIN would silently DROP those
# * rows, and the revenue total would quietly come out too low. With a LEFT JOIN
# * the rows survive with NULLs, so the cleaning step below can see and fix them.
MASTER_QUERY = """
SELECT
    f.fact_id,
    f.customer_id,
    f.plan_id,
    f.date_key,
    f.seats,
    f.mrr,
    f.usage_events,
    f.support_tickets,
    f.discount_pct,
    f.nps_score,
    f.primary_ticket_topic,
    c.company_name,
    c.industry,
    c.segment,
    c.acquisition_channel,
    c.signup_date,
    c.rep_id,
    c.is_annual_contract,
    c.churned_month,
    c.churn_reason_id,
    c.months_active,
    p.plan_name,
    p.tier_rank,
    p.list_price_per_seat,
    r.region_name,
    r.country,
    r.currency,
    d.month_name,
    d.quarter,
    d.is_quarter_end
FROM fact_subscription_monthly AS f
JOIN dim_customer AS c ON f.customer_id = c.customer_id
JOIN dim_plan     AS p ON f.plan_id     = p.plan_id
LEFT JOIN dim_region AS r ON c.region_id = r.region_id
JOIN dim_date     AS d ON f.date_key    = d.date_key
ORDER BY f.customer_id, f.date_key
"""


def load_data():
    """Run MASTER_QUERY against the SQLite file and return one flat DataFrame.

    Returns
    -------
    pd.DataFrame
        One row per customer-month, with every dimension joined on.

    Raises
    ------
    SystemExit
        If the database is missing, with a message saying what to run instead.
        A clear failure here is worth more than a confusing one twenty lines on.
    """
    # * Fail early and explain, rather than letting a missing file surface as a
    # * cryptic "no such table" error from somewhere deeper in pandas.
    if not os.path.exists(config.SQLITE_PATH):
        print("ERROR: the database does not exist yet.")
        print("       Run `make generate` (or `python data_gen.py`) first.")
        sys.exit(1)

    conn = sqlite3.connect(config.SQLITE_PATH)
    try:
        # * pandas can run the query for us: read_sql_query takes a SQL string
        # * and a connection and hands back a DataFrame. That saves writing a
        # * cursor loop by hand.
        df = pd.read_sql_query(MASTER_QUERY, conn)
    finally:
        # * finally: the connection is closed even if the query raised, so a
        # * failed run does not leave the database file locked.
        conn.close()

    # * date_key arrives as a number like 202601. Turn it into a real period so
    # * it sorts and plots as a date rather than as an arbitrary integer.
    df["date_key"] = df["date_key"].astype(int)
    df["month_start"] = pd.to_datetime(df["date_key"].astype(str), format="%Y%m")

    return df


def show_sql_summary(conn_path=None):
    """Print three small SQL results as an ASCII table.

    WHY A SEPARATE FUNCTION
    The rest of this file uses pandas, which is convenient but hides the SQL.
    Running a few queries directly and printing them proves the star schema is
    really a database and not just a pile of CSVs — and `prettytable` is one of
    the libraries used in the certification, so it earns its place here doing
    exactly the job it was designed for.
    """
    conn = sqlite3.connect(conn_path or config.SQLITE_PATH)
    try:
        checks = [
            ("Rows per table",
             "SELECT 'fact' AS table_name, COUNT(*) AS rows FROM fact_subscription_monthly "
             "UNION ALL SELECT 'dim_customer', COUNT(*) FROM dim_customer "
             "UNION ALL SELECT 'dim_plan', COUNT(*) FROM dim_plan "
             "UNION ALL SELECT 'dim_region', COUNT(*) FROM dim_region "
             "UNION ALL SELECT 'dim_rep', COUNT(*) FROM dim_rep "
             "UNION ALL SELECT 'dim_date', COUNT(*) FROM dim_date"),
            ("Revenue by region",
             "SELECT COALESCE(r.region_name, '(no region)') AS region, "
             "       COUNT(DISTINCT f.customer_id) AS customers, "
             "       ROUND(SUM(f.mrr), 2) AS total_mrr "
             "FROM fact_subscription_monthly f "
             "JOIN dim_customer c ON f.customer_id = c.customer_id "
             "LEFT JOIN dim_region r ON c.region_id = r.region_id "
             "GROUP BY r.region_name ORDER BY total_mrr DESC"),
            ("Customers whose region is missing",
             "SELECT COUNT(*) AS customers_with_no_region FROM dim_customer WHERE region_id IS NULL"),
        ]

        for title, query in checks:
            cursor = conn.execute(query)
            headers = [description[0] for description in cursor.description]
            table = PrettyTable(headers)
            # * float_format keeps money and averages to two decimals so the
            # * table lines up instead of showing 16 digits of float noise.
            table.float_format = ".2"
            for row in cursor.fetchall():
                table.add_row(row)
            print(f"\n  SQL — {title}")
            for line in str(table).split("\n"):
                print("    " + line)
    finally:
        conn.close()


