# ============================================================================
# MODELLING — step 4: classification (which customers leave)
# ============================================================================
# THE QUESTION
#   Given what we can see about a customer in their first two months, how likely
#   are they to churn? And — the part that actually matters — at what score
#   should somebody pick up the phone?
#
# WHY ACCURACY IS THE WRONG METRIC HERE, AND PROVES IT IMMEDIATELY
#   Only 20% of customers churn. A model that predicts "nobody churns" for every
#   single customer is 80% ACCURATE and completely worthless: it identifies no
#   one, and a retention team using it would do nothing and lose every leaver.
#
#   So accuracy is reported once, at the start, purely to be dismissed. The
#   working metric is ROC-AUC, which measures whether churners get HIGHER scores
#   than stayers regardless of where the cut-off is drawn — because the cut-off
#   is a business decision, not a statistical one.
#
# THE LEAKAGE GUARD
#   Three columns in this dataset are known only AFTER a customer leaves:
#     churned_month     the label itself
#     churn_reason_id   recorded when they cancel
#     months_active     a churner has fewer months BY CONSTRUCTION
#   Any of them would produce a near-perfect model and a useless one. They are
#   listed in config.LEAKAGE_WARNING and asserted absent by a test.

# * The features offered to the churn models.
CHURN_FEATURES = [
    "usage_per_seat",       # the dominant protective factor
    # * Named support_tickets, but it is already a RATE: prepare_model_frame
    # * aggregates each customer's tickets with the mean over the two-month
    # * baseline window, so this is "tickets per month", not a raw count. A raw
    # * count would be confounded by exposure — a customer with fewer months of
    # * history would appear to raise fewer tickets purely because we watched
    # * them for less time.
    "support_tickets",
    "discount_pct",         # how hard they negotiated
    "nps_score",            # sentiment
    "seats",                # size — turns out not to matter much
    "is_annual_contract",   # commitment
    "industry_risk",        # sector
    "is_smb",               # segment, as a single indicator
]

# ! Columns that must never appear as features. This list is checked at runtime
# ! and raises rather than warning, because a leaky model is not a slightly bad
# ! model — it is a meaningless one that looks excellent.
CHURN_FORBIDDEN = ["churned_month", "churn_reason_id", "months_active", "is_churned"]


def prepare_churn_frame(frame):
    """Return (X, y) for churn modelling, refusing to proceed if leakage exists.

    Uses the same customer-level, fixed-baseline frame as the regression, so the
    two steps describe exactly the same population. Comparing a regression on
    one sample with a classifier on another is a quiet way to contradict
    yourself.
    """
    present = [column for column in CHURN_FORBIDDEN if column in CHURN_FEATURES]
    if present:
        raise ValueError(
            f"Target leakage: {present} would not be known at prediction time. "
            "A model trained on them scores near 1.0 and means nothing."
        )

    X = frame[CHURN_FEATURES].copy()
    y = frame["is_churned"].to_numpy()
    return X, y


def churn_baseline(y):
    """Show what "doing nothing" scores, so every model has something to beat.

    Two baselines, because they fail in different ways:

      majority class   always predicts "stays". High accuracy, zero usefulness.
      random           guesses in proportion to the base rate. This is what
                       ROC-AUC 0.5 means, and it is the floor for that metric.

    Reporting both makes the point that a metric without a baseline is a number
    without a meaning.
    """
    from sklearn.metrics import accuracy_score, roc_auc_score

    majority = np.zeros(len(y), dtype=int)
    return {
        "majority_class_accuracy": round(float(accuracy_score(y, majority)), 4),
        "majority_class_roc_auc": 0.5,
        "churn_rate": round(float(y.mean()), 4),
        "note": (
            "Predicting 'nobody churns' is "
            f"{accuracy_score(y, majority):.0%} accurate and identifies no one. "
            "That is why accuracy is not the metric used below."
        ),
    }


def fit_churn_models(X, y):
    """Train and cross-validate four classifiers, and compare them honestly.

    WHY FOUR RATHER THAN THE BEST ONE
    A single model's score says nothing about whether a simpler model would have
    done as well. Logistic regression is included deliberately: it is
    interpretable, it is what the data was actually generated from, and if it
    matches the complex models then the complexity is buying nothing.

    CLASS IMBALANCE
    With 20% positives, a model can reach high accuracy by leaning toward the
    majority class. Two standard remedies are shown: `class_weight="balanced"`,
    which reweights the loss, and `compute_sample_weight`, which does the same
    thing at the level of individual samples. Both are reported so their effect
    is visible rather than assumed to help.
    """
    from sklearn.ensemble import RandomForestClassifier
    from sklearn.linear_model import LogisticRegression
    from sklearn.model_selection import StratifiedKFold, cross_val_score
    from sklearn.pipeline import Pipeline
    from sklearn.preprocessing import StandardScaler

    cross_validation = StratifiedKFold(
        n_splits=config.CV_FOLDS, shuffle=True, random_state=config.RANDOM_SEED
    )

    def scaled(classifier):
        """Wrap a classifier so its features are standardised first.

        Scaling matters for logistic regression, whose penalty depends on the
        size of the coefficients, and is harmless for trees, which split on
        order rather than distance.
        """
        return Pipeline([("scale", StandardScaler()), ("model", classifier)])

    candidates = {
        "Logistic regression": scaled(LogisticRegression(max_iter=2000)),
        "Logistic regression (balanced)": scaled(
            LogisticRegression(max_iter=2000, class_weight="balanced")
        ),
        "Random forest": RandomForestClassifier(
            n_estimators=300, max_depth=4, random_state=config.RANDOM_SEED
        ),
    }

    # * XGBoost is not part of the certification's imported set (the corpus uses
    # * XGBRegressor only). XGBClassifier is included as a deliberate extension
    # * because gradient boosting is the single most-requested tabular method in
    # * current postings. If the library is unavailable the step is skipped
    # * rather than crashing, and the report says so.
    try:
        from xgboost import XGBClassifier
        candidates["XGBoost"] = XGBClassifier(
            n_estimators=300, max_depth=3, learning_rate=0.05,
            random_state=config.RANDOM_SEED, eval_metric="logloss",
        )
        xgboost_available = True
    except ImportError:
        xgboost_available = False

    results = []
    for name, model in candidates.items():
        auc = cross_val_score(model, X, y, cv=cross_validation, scoring="roc_auc")
        accuracy = cross_val_score(model, X, y, cv=cross_validation, scoring="accuracy")
        results.append({
            "model": name,
            "roc_auc_mean": round(float(auc.mean()), 4),
            "roc_auc_std": round(float(auc.std()), 4),
            "accuracy_mean": round(float(accuracy.mean()), 4),
            "folds": [round(float(score), 4) for score in auc],
        })

    results.sort(key=lambda row: -row["roc_auc_mean"])
    return {
        "cv_folds": config.CV_FOLDS,
        "xgboost_included": xgboost_available,
        "results": results,
        "best_model": results[0]["model"],
        "best_roc_auc": results[0]["roc_auc_mean"],
        "note": (
            "Cross-validated ROC-AUC. The AUC here is high partly because the "
            "data was generated by a logistic process using these very features "
            "— a well-specified model recovers it almost exactly. On real "
            "customer data, where the true process is unknown and includes "
            "factors nobody recorded, expect materially lower."
        ),
    }


def out_of_fold_probabilities(model, X, y):
    """Score every customer with a model that never saw them.

    WHY OUT-OF-FOLD RATHER THAN JUST FITTING ON EVERYTHING
    Fitting on all 200 rows and then scoring those same 200 rows produces
    optimistic numbers, because each customer helped train the model that is
    judging them. Cross-validation avoids that by holding each customer out in
    turn, so every score comes from a model with no knowledge of that customer.

    It costs one extra fit per fold and yields an honest risk list — which is
    exactly what the dashboard displays.
    """
    from sklearn.model_selection import StratifiedKFold, cross_val_predict

    cross_validation = StratifiedKFold(
        n_splits=config.CV_FOLDS, shuffle=True, random_state=config.RANDOM_SEED
    )
    return cross_val_predict(
        model, X, y, cv=cross_validation, method="predict_proba"
    )[:, 1]


def churn_threshold_analysis(model, X, y):
    """Sweep the decision threshold and price the trade-off.

    THE POINT OF THIS FUNCTION
    0.5 is the default cut-off in every library and it is almost never the right
    business decision. It treats a missed churner and a false alarm as equally
    bad, which they are not:

        a MISSED churner   is a lost account — the whole remaining contract value
        a FALSE ALARM      is one retention call

    So the threshold belongs where the two costs balance, which is well below
    0.5. This function works out where, and reports what each choice costs.
    """
    from sklearn.metrics import confusion_matrix, precision_score, recall_score

    # ! OUT-OF-FOLD PREDICTIONS, NOT A SINGLE TEST SPLIT.
    # !
    # ! The first version scored a held-out set of 60 customers, on which the
    # ! model made ZERO false alarms and missed ONE churner. Every threshold from
    # ! 0.45 upward therefore cost exactly the same, the analysis reported a $0
    # ! saving, and the business lesson disappeared — not because thresholding
    # ! does not matter, but because 60 rows are too few to show a trade-off.
    # !
    # ! `cross_val_predict` instead gives every customer a score produced by a
    # ! model that never saw them, using all 200 rows. Same honesty about
    # ! held-out data, four times the evidence.
    probabilities = out_of_fold_probabilities(model, X, y)
    y_test = y

    # * Illustrative costs, stated openly as assumptions rather than presented as
    # * facts. They are the kind of figure a retention team would supply.
    cost_of_missed_churner = 5000.0     # lost account value
    cost_of_false_alarm = 50.0          # an hour of a retention specialist's time

    rows = []
    for threshold in np.arange(0.10, 0.91, 0.05):
        predictions = (probabilities >= threshold).astype(int)
        matrix = confusion_matrix(y_test, predictions)
        # * .ravel() flattens the 2x2 matrix in a fixed order:
        # * true negatives, false positives, false negatives, true positives.
        true_negatives, false_positives, false_negatives, true_positives = matrix.ravel()
        expected_cost = (false_negatives * cost_of_missed_churner
                         + false_positives * cost_of_false_alarm)
        rows.append({
            "threshold": round(float(threshold), 2),
            "true_positives": int(true_positives),
            "false_positives": int(false_positives),
            "false_negatives": int(false_negatives),
            "true_negatives": int(true_negatives),
            "precision": round(float(precision_score(y_test, predictions, zero_division=0)), 3),
            "recall": round(float(recall_score(y_test, predictions, zero_division=0)), 3),
            "expected_cost": round(float(expected_cost), 2),
        })

    cheapest = min(rows, key=lambda row: row["expected_cost"])
    at_default = next(row for row in rows if abs(row["threshold"] - 0.5) < 1e-9)

    return {
        "sweep": rows,
        "cost_assumptions": {
            "missed_churner": cost_of_missed_churner,
            "false_alarm": cost_of_false_alarm,
            "note": "Illustrative figures. A retention team would supply the real ones.",
        },
        "optimal_threshold": cheapest["threshold"],
        "optimal_expected_cost": cheapest["expected_cost"],
        "cost_at_default_threshold": at_default["expected_cost"],
        "saving_vs_default": round(at_default["expected_cost"] - cheapest["expected_cost"], 2),
        "recall_at_optimal": cheapest["recall"],
        "recall_at_default": at_default["recall"],
        "scoring": (
            "Out-of-fold predictions from 5-fold cross-validation: every customer "
            "is scored by a model trained without them."
        ),
        "interpretation": (
            f"With these costs the best cut-off is {cheapest['threshold']:.2f}, not 0.50. "
            f"It catches {cheapest['recall']:.0%} of churners against "
            f"{at_default['recall']:.0%} at the default, and lowers expected cost by "
            f"${at_default['expected_cost'] - cheapest['expected_cost']:,.0f} on this test set."
        ),
    }


def churn_importance(model, X, y):
    """Rank the features by permutation importance, and check them against truth.

    WHY PERMUTATION IMPORTANCE RATHER THAN THE MODEL'S OWN
    A tree reports how much each feature reduced impurity DURING TRAINING, which
    is biased toward features with many possible split points — continuous ones
    like usage_per_seat get an unearned boost over binary ones like
    is_annual_contract. Permutation importance instead shuffles one column at a
    time and measures how much the score falls, which asks the honest question:
    how much does the model actually rely on this?

    It is also model-agnostic, so the same measurement works for a forest, a
    logistic regression or anything else.
    """
    from sklearn.inspection import permutation_importance
    from sklearn.model_selection import train_test_split

    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=config.TEST_SIZE, stratify=y, random_state=config.RANDOM_SEED
    )
    fitted = model.fit(X_train, y_train)

    importance = permutation_importance(
        fitted, X_test, y_test,
        n_repeats=30,                       # repeat the shuffle: one pass is noisy
        random_state=config.RANDOM_SEED,
        scoring="roc_auc",
    )

    ranked = sorted(
        zip(X.columns, importance.importances_mean, importance.importances_std),
        key=lambda item: -item[1],
    )

    truth = config.TRUE_CHURN_COEFFICIENTS
    # * Map the fitted feature name to the config key holding its true effect.
    truth_key = {
        "usage_per_seat": "usage_per_seat", "support_tickets": "support_tickets",
        "discount_pct": "discount_pct", "nps_score": "nps_score",
        "is_smb": "is_smb", "industry_risk": "industry_risk",
        "is_annual_contract": "is_annual_contract",
    }

    return {
        "ranking": [
            {
                "feature": name,
                "importance": round(float(mean), 4),
                "std": round(float(std), 4),
                # * None where the feature was never part of the generating
                # * process — a useful signal, since an important score for a
                # * non-causal feature means the model latched onto noise.
                "true_coefficient": truth.get(truth_key.get(name, ""), None),
            }
            for name, mean, std in ranked
        ],
        "note": (
            "Importance is measured on held-out data by shuffling one column "
            "and re-scoring. A feature with a high importance but no true "
            "coefficient is one the model learned from noise."
        ),
    }


def marginal_versus_conditional(frame):
    """Measure one variable alone, then alongside the others, and compare.

    THE FINDING THIS IS BUILT TO SHOW
    Discount looks almost irrelevant on its own and clearly matters once the
    other features are present. Both numbers are correct; they answer different
    questions, and the gap between them is one of the most common ways an
    analyst misleads themselves with a correlation table.

    Concretely: discount is entangled with segment and usage. Accounts that
    negotiate hard tend also to be smaller and less engaged, and those two
    effects are protective. The raw correlation therefore nets a positive cause
    against negative companions and reports something close to zero.
    """
    import statsmodels.formula.api as smf

    target = "is_churned"
    # * Alone: a one-variable logistic regression.
    alone = smf.logit(f"{target} ~ discount_pct", data=frame).fit(disp=0)

    # * Together: the same variable with company.
    together = smf.logit(
        f"{target} ~ discount_pct + usage_per_seat + seats + nps_score", data=frame
    ).fit(disp=0)

    # ! REPORT THE INTERVALS, AND DO NOT OVERCLAIM FROM THE POINT ESTIMATES.
    # ! An earlier draft of this analysis said the effect "grows several-fold",
    # ! which was true of the numbers and misleading about the evidence: on 200
    # ! customers NEITHER estimate is statistically distinguishable from zero.
    # ! A coefficient that moves a lot between two models, when both intervals
    # ! span zero, is a coefficient we do not yet know anything about.
    alone_interval = alone.conf_int().loc["discount_pct"]
    together_interval = together.conf_int().loc["discount_pct"]

    grows = abs(together.params["discount_pct"]) > abs(alone.params["discount_pct"])
    supported = (alone.pvalues["discount_pct"] < 0.05) or (together.pvalues["discount_pct"] < 0.05)

    return {
        "feature": "discount_pct",
        "marginal_correlation": round(float(frame["discount_pct"].corr(frame[target])), 4),
        "coefficient_alone": round(float(alone.params["discount_pct"]), 4),
        "coefficient_with_others": round(float(together.params["discount_pct"]), 4),
        "ci_alone": [round(float(alone_interval[0]), 3), round(float(alone_interval[1]), 3)],
        "ci_with_others": [round(float(together_interval[0]), 3),
                           round(float(together_interval[1]), 3)],
        "p_value_alone": round(float(alone.pvalues["discount_pct"]), 4),
        "p_value_with_others": round(float(together.pvalues["discount_pct"]), 4),
        "effect_grows_when_controlled": bool(grows),
        "statistically_supported": bool(supported),
        "interpretation": (
            "The coefficient on discount is larger once usage, size and sentiment "
            "are held constant, which is the signature of a variable masked by "
            "correlated companions. BUT: on 200 customers neither estimate is "
            "significantly different from zero, so this is a direction of travel, "
            "not an established effect. Reporting the interval is the difference "
            "between noticing a pattern and claiming one."
            if grows and not supported else
            "Discount shows no effect distinguishable from zero in either model."
        ),
    }


