# ============================================================================
# THE QUESTION
#   "What drives monthly recurring revenue?" — and the answer turns out to be
#   that the question is malformed, which is the first finding.
#
#   MRR is not something to be predicted. It is ARITHMETIC:
#
#       mrr = seats x list_price_per_seat x (1 - discount_pct)
#
#   Every one of those inputs is a column in the data, so a model "explaining"
#   MRR is just re-deriving the invoice. It scores an R² near 1.0 and tells you
#   nothing at all. Recognising that is more valuable than the model would be.
#
#   So the regression is re-aimed at something genuinely uncertain: customer
#   sentiment, measured by NPS. Nobody can compute a customer's satisfaction
#   from a formula, which makes it a real prediction problem.
#
# TWO TOOLS, TWO JOBS — the distinction the whole step is built around
#   statsmodels    EXPLAINS. It reports coefficients, standard errors, p-values
#                  and confidence intervals. It answers "how sure are we, and
#                  could this be chance?"
#   scikit-learn   PREDICTS. It reports how well the model does on data it has
#                  never seen. It does not report p-values, and asking it to is
#                  a category error.
#
#   The certification notes draw exactly this contrast, and step 3 is the place
#   to demonstrate it rather than assert it.

# * The numeric features offered to the model. Declared once, as a list, so the
# * statsmodels formula and the scikit-learn pipeline cannot drift apart — a
# * mismatch between them would make the two tools incomparable, which is the
# * thing this step exists to compare.
MODEL_NUMERIC_FEATURES = [
    "usage_per_seat",       # engagement — the only strong driver, as it turns out
    "support_tickets",      # support load
    "discount_pct",         # how much they negotiated off
    "seats",                # account size
    "is_annual_contract",   # commitment
    "industry_risk",        # sector effect
]

# * Kept separate because it is text, not a number. Turning "SMB" into a number
# * is not a matter of relabelling: 1 and 2 imply an order that does not exist.
# * It is one-hot encoded instead, giving each segment its own yes/no column.
MODEL_CATEGORICAL_FEATURES = ["segment"]

TARGET = "nps_score"


def prepare_model_frame(df):
    """Build the modelling table: one row per customer, with features and target.

    WHY ONE ROW PER CUSTOMER
    The fact table has one row per customer-MONTH, so a customer appears up to
    four times. Modelling at that grain would violate the independence
    assumption every standard error depends on: four rows about the same
    customer are not four independent observations, and treating them as such
    makes the confidence intervals far too narrow and the p-values far too
    small. It is a quiet way to manufacture significance.

    So the features are averaged per customer and the target is averaged too.
    One customer, one row, one vote.

    WHY THE BASELINE WINDOW
    Only the first two months are used. A customer who churned has fewer rows
    than one who stayed, so averaging over "all the months they happen to have"
    would measure different customers over different periods — the outcome
    leaking into the features. Using a fixed window removes that entirely.
    """
    baseline = df[df["date_key"].isin(config.MONTHS[:2])].copy()

    per_customer = baseline.groupby("customer_id").agg(
        usage_per_seat=("usage_per_seat", "mean"),
        support_tickets=("support_tickets", "mean"),
        discount_pct=("discount_pct", "mean"),
        seats=("seats", "mean"),
        nps_score=("nps_score", "mean"),
        # * Revenue per customer. Not a churn feature — it was already shown to
        # * carry almost no signal — but the risk table has to say what each
        # * account is worth before anyone decides to call them.
        mrr=("mrr", "mean"),
        # * "max" rather than "mean" for these two: they are constant per
        # * customer, so any aggregation returns the same value, and max is the
        # * clearest way to say "the customer's value".
        is_annual_contract=("is_annual_contract", "max"),
        segment=("segment", "max"),
        industry=("industry", "max"),
        # * Carried through for DISPLAY only, never as features. The dashboard's
        # * risk table has to name the account and say where it is, and a
        # * customer id alone is useless to a retention team.
        company_name=("company_name", "max"),
        region_name=("region_name", "max"),
        # * Carried through for diagnostics, never used as a feature.
        is_churned=("is_churned", "max"),
    ).reset_index()

    industry_risk = {d["industry"]: d["churn_risk_index"] for d in config.INDUSTRIES}
    per_customer["industry_risk"] = per_customer["industry"].map(industry_risk).fillna(0.0)

    # * A binary flag for the SMB segment.
    # * The segment column is text, which a scikit-learn model cannot consume.
    # * statsmodels handles it directly with C(segment) in a formula, and the
    # * scikit-learn pipeline one-hot encodes it — but several analyses here want
    # * a single simple indicator, so it is built once, here, rather than three
    # * times in three different places.
    per_customer["is_smb"] = (per_customer["segment"] == "SMB").astype(int)

    # * Drop rows missing anything the model needs. listwise deletion is the
    # * simplest honest option, and the count is reported so its cost is visible.
    needed = [TARGET] + MODEL_NUMERIC_FEATURES
    before = len(per_customer)
    per_customer = per_customer.dropna(subset=needed).reset_index(drop=True)
    per_customer.attrs["dropped_for_missing"] = before - len(per_customer)

    return per_customer


def mrr_is_an_identity(df):
    """Show that MRR is fully determined by its own components.

    A deliberately anticlimactic model. It is included because the anticlimax IS
    the finding: a near-perfect R² here would look impressive on a slide and
    mean nothing, since the "prediction" is the invoice formula written out
    again. An analyst who cannot tell the difference between explaining a number
    and re-deriving it will produce confident nonsense.
    """
    import statsmodels.formula.api as smf

    model = smf.ols("mrr ~ seats + list_price_per_seat + discount_pct", data=df).fit()

    return {
        "question": "Can MRR be predicted?",
        "verdict": "It is arithmetic, not a prediction problem",
        "r_squared": round(float(model.rsquared), 4),
        "formula": "mrr = seats x list_price_per_seat x (1 - discount_pct)",
        "note": (
            "The R² is high because the right-hand side IS the invoice formula. "
            "This model has no predictive content and is reported only to show "
            "the difference between explaining a quantity and re-deriving it."
        ),
    }


def fit_nps_ols(frame):
    """Explain NPS with statsmodels: coefficients, p-values, confidence intervals.

    THE ONE THING TO NOTICE IN THE OUTPUT
    The overall F-test will be overwhelmingly significant (p close to zero)
    while most INDIVIDUAL coefficients are not. Those two statements are not in
    conflict, and reading them correctly is a genuinely useful skill:

        F-test            asks "does this set of variables explain anything at
                          all, compared with no variables?"
        individual t-test asks "does THIS variable add anything, given all the
                          others are already in the model?"

    A variable can fail the second while the group passes the first — most of
    these predictors are correlated with usage, so once usage is in the model
    they have little left to contribute. That is not a bug in the data; it is
    what multicollinearity looks like.
    """
    import statsmodels.formula.api as smf

    # * The formula is written as a readable string. That is the whole appeal of
    # * statsmodels' formula API: the model specification looks like the
    # * equation in a textbook, so a reader can check it against the question.
    formula = (
        f"{TARGET} ~ "
        + " + ".join(MODEL_NUMERIC_FEATURES)
        + " + C(segment)"       # C(...) tells statsmodels this is categorical,
                                # so it creates dummy columns automatically
    )

    model = smf.ols(formula, data=frame).fit()

    # * Build a clean coefficient table rather than dumping the summary text,
    # * so the numbers can be written to JSON and rendered on the dashboard.
    coefficients = []
    for name in model.params.index:
        coefficients.append({
            "term": name,
            "coefficient": round(float(model.params[name]), 4),
            "std_error": round(float(model.bse[name]), 4),
            "t_statistic": round(float(model.tvalues[name]), 3),
            "p_value": round(float(model.pvalues[name]), 5),
            "ci_low": round(float(model.conf_int().loc[name, 0]), 4),
            "ci_high": round(float(model.conf_int().loc[name, 1]), 4),
            # * "significant" is a shortcut for "the 95% interval excludes zero".
            # * Stated that way, the threshold is visible rather than implied.
            "significant_at_5pct": bool(model.pvalues[name] < 0.05),
        })

    significant = [c for c in coefficients if c["significant_at_5pct"] and c["term"] != "Intercept"]

    return {
        "question": f"What explains {TARGET}?",
        "formula": formula,
        "n_observations": int(model.nobs),
        "r_squared": round(float(model.rsquared), 4),
        "adjusted_r_squared": round(float(model.rsquared_adj), 4),
        "f_statistic": round(float(model.fvalue), 3),
        "f_p_value": float(model.f_pvalue),
        "coefficients": coefficients,
        "significant_terms": [c["term"] for c in significant],
        "interpretation": (
            "The model as a whole is highly significant, but only "
            f"{len(significant)} of {len(coefficients) - 1} terms is individually "
            "significant. The overall test and the individual tests answer "
            "different questions, and a variable can matter as part of a group "
            "while adding nothing on its own."
        ),
    }


def compare_parsimony(frame):
    """Does the six-feature model beat the one-feature model?

    WHY THIS COMPARISON IS WORTH MAKING
    If a single variable does almost all the work, every additional term is
    costing a reader's attention and buying nothing. The usual measure is the
    ADJUSTED R², which penalises extra terms rather than rewarding them — plain
    R² can only ever go up as features are added, even when they are noise.
    """
    import statsmodels.formula.api as smf

    full = smf.ols(
        f"{TARGET} ~ " + " + ".join(MODEL_NUMERIC_FEATURES) + " + C(segment)",
        data=frame,
    ).fit()
    single = smf.ols(f"{TARGET} ~ usage_per_seat", data=frame).fit()
    empty = smf.ols(f"{TARGET} ~ 1", data=frame).fit()   # intercept only: the mean

    return [
        {
            "model": "Mean only (no features)",
            "terms": 0,
            "r_squared": round(float(empty.rsquared), 4),
            "adjusted_r_squared": round(float(empty.rsquared_adj), 4),
        },
        {
            "model": "usage_per_seat only",
            "terms": 1,
            "r_squared": round(float(single.rsquared), 4),
            "adjusted_r_squared": round(float(single.rsquared_adj), 4),
        },
        {
            "model": "All features",
            "terms": len(MODEL_NUMERIC_FEATURES) + frame["segment"].nunique() - 1,
            "r_squared": round(float(full.rsquared), 4),
            "adjusted_r_squared": round(float(full.rsquared_adj), 4),
        },
    ]


def predict_nps_out_of_sample(frame):
    """Predict NPS with scikit-learn, scored on data the models never saw.

    WHY CROSS-VALIDATION RATHER THAN A SINGLE SPLIT
    A single train/test split gives one number that depends on which rows
    happened to land in the test set. With 200 customers that is a lot of coin
    flip. K-fold cross-validation repeats the experiment K times on K different
    splits and reports the spread, so we can see whether a difference between
    two models is real or just which rows were held out.

    WHY A BASELINE IS INCLUDED
    A model must beat simply predicting the average. Without that comparison an
    R² of 0.17 is uninterpretable — it might be a real signal or it might be
    what you get for free. The baseline is a DummyRegressor, which always
    predicts the training mean and therefore scores R² ≈ 0 by definition. Every
    real model is measured against it.
    """
    from sklearn.compose import ColumnTransformer
    from sklearn.dummy import DummyRegressor
    from sklearn.ensemble import GradientBoostingRegressor
    from sklearn.impute import SimpleImputer
    from sklearn.linear_model import LinearRegression, Ridge
    from sklearn.model_selection import KFold, cross_val_score
    from sklearn.pipeline import Pipeline
    from sklearn.preprocessing import OneHotEncoder, StandardScaler

    X = frame[MODEL_NUMERIC_FEATURES + MODEL_CATEGORICAL_FEATURES]
    y = frame[TARGET].to_numpy()

    # ? ColumnTransformer applies DIFFERENT preprocessing to different columns
    # ? in one step. Numbers get scaled; text gets one-hot encoded. Doing it in
    # ? one object means the same transformation is applied to every fold, which
    # ? is what stops preprocessing from leaking information between them.
    preprocess = ColumnTransformer(transformers=[
        ("numeric", Pipeline([
            # * SimpleImputer fills gaps so a model never sees NaN. The median
            # * is used for the same reason as in the cleaning step: it resists
            # * the few extreme accounts.
            ("impute", SimpleImputer(strategy="median")),
            # * Scaling puts every numeric feature on the same footing. It
            # * matters for Ridge, which penalises coefficients, and is harmless
            # * for the tree model.
            ("scale", StandardScaler()),
        ]), MODEL_NUMERIC_FEATURES),
        ("categorical", OneHotEncoder(handle_unknown="ignore"), MODEL_CATEGORICAL_FEATURES),
    ])

    models = {
        "Mean baseline (predict the average)": DummyRegressor(strategy="mean"),
        "Linear regression, usage only": Pipeline([
            ("prep", ColumnTransformer(
                transformers=[("numeric", StandardScaler(), ["usage_per_seat"])],
                remainder="drop")),
            ("model", LinearRegression()),
        ]),
        "Ridge, all features": Pipeline([("prep", preprocess), ("model", Ridge(alpha=1.0))]),
        "Gradient boosting, all features": Pipeline([
            ("prep", preprocess),
            # * A small forest on purpose. 200 rows cannot support a large one;
            # * deep trees would memorise the customers rather than learn a
            # * pattern, and cross-validation would show it.
            ("model", GradientBoostingRegressor(n_estimators=200, max_depth=2,
                                                learning_rate=0.05,
                                                random_state=config.RANDOM_SEED)),
        ]),
    }

    # * KFold splits the rows into 5 groups and, five times over, trains on four
    # * and tests on the fifth. shuffle=True with a fixed seed means everyone
    # * gets a turn in the test set and the result is reproducible.
    cross_validation = KFold(n_splits=config.CV_FOLDS, shuffle=True,
                             random_state=config.RANDOM_SEED)

    results = []
    for name, model in models.items():
        scores = cross_val_score(model, X, y, cv=cross_validation,
                                 scoring="r2", n_jobs=1)
        results.append({
            "model": name,
            "mean_r2": round(float(scores.mean()), 4),
            "std_r2": round(float(scores.std()), 4),
            "folds": [round(float(score), 4) for score in scores],
        })

    # * Sort by mean R², best first, so the table reads as a ranking.
    results.sort(key=lambda row: -row["mean_r2"])
    best = results[0]
    baseline = next(r for r in results if "baseline" in r["model"])

    return {
        "cv_folds": config.CV_FOLDS,
        "n_observations": int(len(frame)),
        "results": results,
        "best_model": best["model"],
        "best_mean_r2": best["mean_r2"],
        "baseline_r2": baseline["mean_r2"],
        "improvement_over_baseline": round(best["mean_r2"] - baseline["mean_r2"], 4),
        "interpretation": (
            "Cross-validated R² on unseen customers. The spread across folds "
            "matters as much as the mean: with 200 customers a difference "
            "smaller than the fold-to-fold variation is not a real difference."
        ),
    }


