# THE QUESTION
#   If we stop imposing the labels we already have (SMB / Mid-Market /
#   Enterprise) and simply ask the data to group itself, what comes back? Are
#   there distinct kinds of customer, or one continuum that we have been
#   chopping into buckets?
#
# THE TRAP THIS STEP IS BUILT TO EXPOSE
#   KMeans ALWAYS returns the number of clusters you ask for. Ask for four and
#   you get four, drawn confidently, whether or not four groups exist. It is not
#   a test for structure; it is a way of partitioning data that may have none.
#
#   So the honest question is not "what are the clusters?" but "is there any
#   cluster structure here at all?" — and the way to answer that is to also run
#   methods that are ALLOWED to say no. DBSCAN and HDBSCAN both can, because
#   they look for densely packed regions and will label a point as noise rather
#   than force it into a group.
#
#   They are run here alongside KMeans precisely so the two answers can be
#   compared. If the density methods find nothing, the KMeans groups are a
#   partition, not a discovery — and calling them "customer segments" in a
#   report would be a mistake.

# * The features offered to the clustering. These describe the customer's
# * observable commercial profile; the churn label is deliberately absent,
# * because clustering on an outcome would just reproduce the outcome.
CLUSTER_FEATURES = [
    "usage_per_seat",
    "support_tickets",
    "discount_pct",
    "seats",
    "nps_score",
    "mrr",
]

# * Silhouette runs from -1 to 1 and measures how much closer a point is to its
# * own cluster than to the next nearest one. Conventional reading:
# *     above 0.70  strong structure
# *     0.50-0.70   reasonable
# *     0.25-0.50   weak, possibly artificial
# *     below 0.25  no substantial structure found
# * Recorded here as a constant so the verdict is applied consistently rather
# * than judged by eye once the numbers are on screen.
SILHOUETTE_BANDS = [
    (0.70, "strong structure"),
    (0.50, "reasonable structure"),
    (0.25, "weak — possibly artificial"),
    (-1.00, "no substantial structure"),
]


def _describe_silhouette(score):
    """Turn a silhouette score into the conventional verbal verdict."""
    for threshold, label in SILHOUETTE_BANDS:
        if score >= threshold:
            return label
    return "no substantial structure"


def prepare_cluster_frame(df):
    """Build the customer-level frame used for clustering.

    The same shape as the modelling frame: one row per customer, features
    averaged over the fixed two-month baseline.

    ! NOTE THE dropna(subset=...) — THE SUBSET IS NOT OPTIONAL.
    ! A bare `.dropna()` removes any row containing a NaN in ANY column. In the
    ! ! customer table `churned_month` is NaN for every customer who STAYED, so
    ! ! a bare dropna silently reduces 200 customers to the 40 who churned and
    ! ! clusters only the leavers. That mistake was made during the exploration
    ! ! for this step, and the result looked plausible enough to be missed.
    """
    baseline = df[df["date_key"].isin(config.MONTHS[:2])]

    per_customer = baseline.groupby("customer_id").agg(
        usage_per_seat=("usage_per_seat", "mean"),
        support_tickets=("support_tickets", "mean"),
        discount_pct=("discount_pct", "mean"),
        seats=("seats", "mean"),
        nps_score=("nps_score", "mean"),
        mrr=("mrr", "mean"),
        segment=("segment", "max"),
        industry=("industry", "max"),
        is_churned=("is_churned", "max"),
    ).reset_index()

    before = len(per_customer)
    per_customer = per_customer.dropna(subset=CLUSTER_FEATURES).reset_index(drop=True)
    per_customer.attrs["dropped_for_missing"] = before - len(per_customer)
    return per_customer


def kmeans_search(X, k_range=None):
    """Run KMeans for a range of k and score each result four different ways.

    WHY FOUR METRICS RATHER THAN ONE
    They disagree, and the disagreement is informative:

      inertia          always falls as k rises, so it can never choose k on its
                       own. It is read as an ELBOW — where the curve stops
                       falling steeply — which is a judgement, not a number.
      silhouette       rewards points being closer to their own group. Comparable
                       across k, which is what makes it usable.
      davies-bouldin   LOWER is better: it compares within-cluster spread to
                       between-cluster distance. The only metric here where you
                       want a small number.
      calinski-harabasz HIGHER is better, and rises steeply with k, so like
                       inertia it is read for shape rather than as a maximum.

    Choosing k from one metric is how people end up with seven segments nobody
    asked for.
    """
    from sklearn.cluster import KMeans
    from sklearn.metrics import (calinski_harabasz_score, davies_bouldin_score,
                                 silhouette_score)

    if k_range is None:
        k_range = config.CLUSTER_K_RANGE

    rows = []
    for k in k_range:
        model = KMeans(n_clusters=k, n_init=config.CLUSTER_KMEANS_N_INIT,
                       random_state=config.RANDOM_SEED).fit(X)
        rows.append({
            "k": int(k),
            "inertia": round(float(model.inertia_), 2),
            "silhouette": round(float(silhouette_score(X, model.labels_)), 4),
            "davies_bouldin": round(float(davies_bouldin_score(X, model.labels_)), 4),
            "calinski_harabasz": round(float(calinski_harabasz_score(X, model.labels_)), 2),
        })

    best = max(rows, key=lambda row: row["silhouette"])
    return {
        "metrics_by_k": rows,
        "best_k_by_silhouette": best["k"],
        "best_silhouette": best["silhouette"],
        "verdict": _describe_silhouette(best["silhouette"]),
    }


def density_based_clustering(X):
    """Run DBSCAN and HDBSCAN — the methods that are allowed to find nothing.

    WHY THESE TWO MATTER MORE THAN THEIR SCORES
    KMeans and DBSCAN answer different questions. KMeans asks "how do I split
    these points into k groups?" and always succeeds. DBSCAN asks "are there
    regions of the space that are much denser than the rest?" and is free to
    answer no.

    HDBSCAN removes DBSCAN's main weakness — the single fixed radius `eps` — by
    looking across a range of densities, and it labels outliers as noise (-1)
    rather than absorbing them into the nearest group.

    A result where HDBSCAN assigns EVERY point to noise is a strong statement:
    there is no dense island anywhere in this feature space. That is a finding,
    not a failure.
    """
    from sklearn.cluster import DBSCAN

    sweeps = []
    for eps in [1.8, 2.2, 2.6, 3.2, 4.0]:
        model = DBSCAN(eps=eps, min_samples=5).fit(X)
        labels = model.labels_
        # * -1 is DBSCAN's noise label, not a cluster, so it is excluded from
        # * the count of clusters found.
        found = len(set(labels)) - (1 if -1 in labels else 0)
        sweeps.append({
            "eps": eps,
            "clusters_found": int(found),
            "noise_points": int((labels == -1).sum()),
            "noise_share": round(float((labels == -1).mean()), 4),
        })

    result = {
        "dbscan_sweep": sweeps,
        "dbscan_clusters_at_any_eps": max(row["clusters_found"] for row in sweeps),
    }

    try:
        import hdbscan
        model = hdbscan.HDBSCAN(min_cluster_size=12).fit(X)
        labels = model.labels_
        found = len(set(labels)) - (1 if -1 in labels else 0)
        result["hdbscan"] = {
            "clusters_found": int(found),
            "noise_points": int((labels == -1).sum()),
            "noise_share": round(float((labels == -1).mean()), 4),
        }
    except ImportError:
        result["hdbscan"] = {"error": "hdbscan not installed"}

    result["interpretation"] = (
        "Density-based methods look for dense regions and are free to find none. "
        f"DBSCAN found at most {result['dbscan_clusters_at_any_eps']} cluster(s) across "
        f"the whole eps sweep, and HDBSCAN classified "
        f"{result['hdbscan'].get('noise_share', 0):.0%} of customers as noise. "
        "Taken together they indicate a continuum rather than distinct groups."
    )
    return result


def cluster_stability(X, k):
    """Rerun KMeans with ten different random seeds and compare the partitions.

    WHY THIS IS THE FIRST THING TO CHECK
    KMeans starts from randomly placed centres, so a run is one sample from a
    distribution of possible answers. If ten seeds give ten different groupings,
    the clusters describe the algorithm's starting point rather than the data.

    The Adjusted Rand Index measures agreement between two partitions: 1.0 means
    identical, 0 means no better than random. It is "adjusted" because it
    corrects for the agreement two random partitions would show by chance, which
    plain accuracy would not.
    """
    from sklearn.cluster import KMeans
    from sklearn.metrics import adjusted_rand_score

    partitions = [
        KMeans(n_clusters=k, n_init=config.CLUSTER_KMEANS_N_INIT, random_state=seed)
        .fit_predict(X)
        for seed in range(10)
    ]

    # * Compare every later run against the first. Comparing all pairs would be
    # * better still; one reference is enough to expose instability and keeps
    # * the output readable.
    scores = [adjusted_rand_score(partitions[0], other) for other in partitions[1:]]

    mean_score = float(np.mean(scores))

    # * Bands, applied consistently rather than judged by eye once the number is
    # * on screen. An earlier draft used a single 0.90 cut-off, which labelled a
    # * score of 0.87 "unstable" — too harsh, and it would have overstated the
    # * finding. These bands follow the usual reading of the index.
    if mean_score >= 0.90:
        verdict = "highly stable — the same grouping is found from any starting point"
    elif mean_score >= 0.75:
        verdict = "moderately stable — the broad shape holds, the edges move"
    else:
        verdict = "unstable — the grouping depends on where the algorithm started"

    return {
        "k": int(k),
        "runs": len(partitions),
        "mean_adjusted_rand_index": round(mean_score, 4),
        "min": round(float(np.min(scores)), 4),
        "max": round(float(np.max(scores)), 4),
        "verdict": verdict,
    }


def reduce_dimensions(X):
    """Project the customers into two dimensions three different ways.

    WHY THREE, AND WHY THE PICTURES MUST BE READ CAREFULLY
    PCA, t-SNE and UMAP all flatten six dimensions into two, and each distorts
    differently:

      PCA     a linear projection. Distances and cluster sizes stay roughly
              meaningful, but it can only show structure that is aligned with
              the directions of greatest variance.
      t-SNE   preserves LOCAL neighbourhoods — who is near whom — and is
              excellent for seeing grouping. It does NOT preserve distances, so
              the gaps between clusters in a t-SNE plot mean nothing.
      UMAP    similar to t-SNE, generally faster and better at keeping global
              shape, and equally not to be measured with a ruler.

    A silhouette score computed in a 2-D projection is therefore not comparable
    to one computed in the original space. Projections are for looking at, not
    for scoring.
    """
    import time
    from sklearn.decomposition import PCA
    from sklearn.manifold import TSNE

    output = {}

    principal = PCA(n_components=2, random_state=config.RANDOM_SEED)
    output["pca"] = principal.fit_transform(X)
    output["pca_variance_explained"] = round(
        float(principal.explained_variance_ratio_.sum()), 4)

    started = time.time()
    output["tsne"] = TSNE(n_components=2, perplexity=30, random_state=config.RANDOM_SEED,
                          init="pca").fit_transform(X)
    output["tsne_seconds"] = round(time.time() - started, 2)

    try:
        import umap
        started = time.time()
        # * n_neighbors controls the balance between local and global structure:
        # * small values see fine detail, large values see the overall shape.
        # * 15 is the library's default and a reasonable middle.
        output["umap"] = umap.UMAP(n_components=2, n_neighbors=15,
                                   random_state=config.RANDOM_SEED).fit_transform(X)
        output["umap_seconds"] = round(time.time() - started, 2)
    except ImportError:
        output["umap"] = None

    return output


def cluster_profiles(frame, labels, k):
    """Describe what each cluster actually contains.

    A cluster number is meaningless on its own. All that matters is whether the
    group has a coherent, describable profile — and whether that profile differs
    from the others by more than sampling noise.
    """
    working = frame.copy()
    working["cluster"] = labels

    profiles = []
    for cluster_id, group in working.groupby("cluster"):
        profile = {
            "cluster": int(cluster_id),
            "customers": int(len(group)),
            "churn_rate": round(float(group["is_churned"].mean()), 4),
        }
        for feature in CLUSTER_FEATURES:
            profile[feature] = round(float(group[feature].mean()), 2)
        # * Which segment dominates this cluster? If a cluster is essentially
        # * one existing segment, it has told us nothing we did not already know.
        profile["dominant_segment"] = group["segment"].mode().iat[0]
        profile["segment_purity"] = round(float(group["segment"].value_counts(normalize=True).iloc[0]), 3)
        profiles.append(profile)

    return sorted(profiles, key=lambda row: -row["customers"])


def clusters_versus_known_labels(frame, labels):
    """Do the discovered clusters line up with anything we already knew?

    A cluster that agrees strongly with the customer's existing segment is not a
    discovery — it is the segment table rediscovered with more effort. A cluster
    that cuts ACROSS segments is the interesting case, because it suggests
    something the existing labels do not capture.
    """
    working = frame.copy()
    working["cluster"] = labels

    # * Crosstab: rows are clusters, columns are the known segments. `normalize`
    # * turns counts into shares so purity is readable at a glance.
    crosstab = pd.crosstab(working["cluster"], working["segment"])
    shares = pd.crosstab(working["cluster"], working["segment"], normalize="index")

    return {
        "counts": {str(cluster): row.to_dict() for cluster, row in crosstab.iterrows()},
        "segment_share_within_cluster": {
            str(cluster): {segment: round(float(value), 3) for segment, value in row.items()}
            for cluster, row in shares.iterrows()
        },
        "churn_rate_by_cluster": {
            str(cluster): round(float(group["is_churned"].mean()), 4)
            for cluster, group in working.groupby("cluster")
        },
        "interpretation": (
            "If a cluster is dominated by one existing segment, the algorithm has "
            "recovered a label we already had. Only clusters that mix segments are "
            "telling us something new."
        ),
    }


