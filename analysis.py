    baseline = churn_baseline(y_churn)
    comparison = fit_churn_models(X_churn, y_churn)
    churn_model, X_train, X_test, y_train, y_test = _fit_churn_test_model(X_churn, y_churn)
    threshold = churn_threshold_analysis(churn_model, X_churn, y_churn)
    importance = churn_importance(churn_model, X_churn, y_churn)
    mvc = marginal_versus_conditional(frame)

    print(f"\n  CLASSIFICATION — who churns?  (n={len(y_churn)}, "
          f"{int(y_churn.sum())} churners, {y_churn.mean():.1%})")
    print(f"    baseline            predicting 'nobody churns' is "
          f"{baseline['majority_class_accuracy']:.1%} accurate and finds nobody")
    print(f"    {'model':<34}{'ROC-AUC':>10}{'sd':>8}{'accuracy':>11}")
    for row in comparison["results"]:
        print(f"    {row['model']:<34}{row['roc_auc_mean']:>10.3f}"
              f"{row['roc_auc_std']:>8.3f}{row['accuracy_mean']:>11.3f}")

    print(f"\n    THRESHOLD — 0.50 is a library default, not a decision")
    print(f"    {'thresh':>8}{'caught':>9}{'missed':>9}{'false alarms':>15}{'precision':>11}")
    for row in threshold["sweep"]:
        if row["threshold"] in (0.20, 0.30, 0.40, 0.50, 0.60, 0.70):
            print(f"    {row['threshold']:>8.2f}{row['recall']:>9.0%}"
                  f"{row['false_negatives']:>9}{row['false_positives']:>15}"
                  f"{row['precision']:>11.2f}")
    print(f"    -> {threshold['interpretation']}")

    print(f"\n    IMPORTANCE — what the model relies on")
    for row in importance["ranking"][:5]:
        truth = ("no true effect" if row["true_coefficient"] is None
                 else f"true {row['true_coefficient']:+.2f}")
        print(f"    {row['feature']:<22}{row['importance']:>+8.4f}   {truth}")

    print(f"\n    MARGINAL vs CONDITIONAL — discount_pct")
    print(f"    alone              coef {mvc['coefficient_alone']:>+7.3f}  "
          f"95% CI [{mvc['ci_alone'][0]:+.2f}, {mvc['ci_alone'][1]:+.2f}]  "
          f"p={mvc['p_value_alone']:.3f}")
    print(f"    with the others    coef {mvc['coefficient_with_others']:>+7.3f}  "
          f"95% CI [{mvc['ci_with_others'][0]:+.2f}, {mvc['ci_with_others'][1]:+.2f}]  "
          f"p={mvc['p_value_with_others']:.3f}")
    supported = "yes" if mvc["statistically_supported"] else "NO — not on this sample"
    print(f"    -> the coefficient grows when controlled: "
          f"{'yes' if mvc['effect_grows_when_controlled'] else 'no'}; "
          f"statistically supported: {supported}")

    # --- STEP 5: clustering -------------------------------------------------
    cluster_frame = prepare_cluster_frame(df)
    cluster_features = cluster_frame[CLUSTER_FEATURES]
    from sklearn.preprocessing import StandardScaler as _Scaler
    X_cluster = _Scaler().fit_transform(cluster_features)

    search = kmeans_search(X_cluster)
    density = density_based_clustering(X_cluster)
    best_k = search["best_k_by_silhouette"]
    stability = cluster_stability(X_cluster, best_k)

    from sklearn.cluster import KMeans as _KMeans
    cluster_labels = _KMeans(n_clusters=best_k, n_init=config.CLUSTER_KMEANS_N_INIT,
                             random_state=config.RANDOM_SEED).fit_predict(X_cluster)
    profiles = cluster_profiles(cluster_frame, cluster_labels, best_k)
    alignment = clusters_versus_known_labels(cluster_frame, cluster_labels)
    embedding = reduce_dimensions(X_cluster)

    print(f"\n  CLUSTERING — are there natural segments?  (n={len(cluster_frame)})")
    print(f"    {'k':>3}{'silhouette':>12}{'davies-bouldin':>17}{'calinski':>11}")
    for row in search["metrics_by_k"]:
        print(f"    {row['k']:>3}{row['silhouette']:>12.3f}"
              f"{row['davies_bouldin']:>17.3f}{row['calinski_harabasz']:>11.1f}")
    print(f"    -> best k={best_k}, silhouette {search['best_silhouette']:.3f} "
          f"({search['verdict']})")

    print(f"\n    DENSITY METHODS — the ones allowed to find nothing")
    for row in density["dbscan_sweep"]:
        print(f"    DBSCAN eps={row['eps']:<5} clusters={row['clusters_found']:<3} "
              f"noise {row['noise_points']:>3} ({row['noise_share']:.0%})")
    hdb = density["hdbscan"]
    print(f"    HDBSCAN            clusters={hdb.get('clusters_found', 'n/a')}   "
          f"noise {hdb.get('noise_points', 'n/a')} ({hdb.get('noise_share', 0):.0%})")

    print(f"\n    STABILITY          ARI across 10 seeds: "
          f"{stability['mean_adjusted_rand_index']:.3f} -> {stability['verdict']}")
    print(f"    PROJECTIONS        2-D captures "
          f"{embedding['pca_variance_explained']:.1%} of variance; "
          f"t-SNE {embedding['tsne_seconds']}s"
          + (f", UMAP {embedding['umap_seconds']}s" if embedding.get("umap") is not None else ""))

    print(f"\n    CLUSTER PROFILES")
    for profile in profiles:
        print(f"    cluster {profile['cluster']}  n={profile['customers']:<4} "
              f"churn {profile['churn_rate']:>5.1%}  seats {profile['seats']:>7.1f}  "
              f"mrr ${profile['mrr']:>10,.0f}  usage {profile['usage_per_seat']:>5.1f}  "
              f"-> mostly {profile['dominant_segment']} ({profile['segment_purity']:.0%})")

    # * Computed once and shared by the threshold sweep, the risk table and the
    # * dashboard. Computing it twice would be wasteful, and worse, the two
    # * copies could disagree if the model or the split ever changed.
    churn_probabilities = out_of_fold_probabilities(churn_model, X_churn, y_churn)
