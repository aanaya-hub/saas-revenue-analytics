# WHY THIS EXISTS AS A SEPARATE STRUCTURE
#   The dashboard is deployed to a free host whose Python bundle limit is 500 MB.
#   The analysis stack — xgboost alone is about 200 MB — is roughly 1 GB, so the
#   dashboard must never import it. Instead, everything it displays is computed
#   here and written to reports/results.json as plain numbers.
#
#   That has a useful side effect: models never re-train because somebody moved
#   a slider. The dashboard does arithmetic on precomputed probabilities, which
#   is why it can respond instantly and why it needs no machine-learning library
#   at all.

def build_dashboard_payload(df, frame, probabilities, cluster_labels):
    """Assemble the customer-level table and the aggregates the dashboard renders.

    Returns a dictionary small enough to ship in a JSON file — a few hundred
    kilobytes — while still carrying enough detail for every chart to be drawn
    in the browser rather than as a pre-rendered image.

    The charts are built from these numbers, NOT from the PNG files in
    reports/figures. Those PNGs are gitignored, so a deployed copy of this
    project would not have them; and Plotly charts can be filtered and zoomed,
    which a picture cannot.
    """
    import pandas as pd

    working = frame.copy()
    working["churn_probability"] = probabilities
    working["cluster"] = cluster_labels

    # --- Monthly revenue series ---------------------------------------------
    # * Aggregated per month so the executive chart can show the trend. The
    # * customer count is carried alongside the money because MRR can fall
    # * either from losing accounts or from shrinking ones, and those are
    # * different problems.
    monthly = df.groupby(["date_key", "month_name"], sort=True).agg(
        mrr=("mrr", "sum"), customers=("customer_id", "nunique")
    ).reset_index().sort_values("date_key")
    monthly["arpa"] = (monthly["mrr"] / monthly["customers"]).round(2)

    # --- Revenue by dimension ------------------------------------------------
    def revenue_by(column):
        """Total and average revenue per value of `column`.

        A nested function because the same three aggregations are needed for
        segment, region and industry. Written once, so all three breakdowns are
        computed identically — three hand-written blocks would eventually
        disagree about something.
        """
        grouped = df.groupby(column).agg(
            mrr=("mrr", "sum"),
            customers=("customer_id", "nunique"),
            mean_mrr=("mrr", "mean"),
        ).reset_index().sort_values("mrr", ascending=False)
        return [
            {"category": str(row[column]), "mrr": round(float(row["mrr"]), 2),
             "customers": int(row["customers"]), "mean_mrr": round(float(row["mean_mrr"]), 2)}
            for _, row in grouped.iterrows()
        ]

    # --- The customer risk table --------------------------------------------
    # * One row per customer. This is the table a retention team would work
    # * from, and the data behind the churn scatter.
    customers = []
    for _, row in working.iterrows():
        probability = float(row["churn_probability"])
        # * Bands rather than a bare number, because a call list needs an
        # * ordering, not a decimal. The boundaries are stated here so the
        # * dashboard labels and the analysis agree.
        if probability >= 0.60:
            band = "High"
        elif probability >= 0.30:
            band = "Medium"
        else:
            band = "Low"
        customers.append({
            "customer_id": int(row["customer_id"]),
            "company": str(row["company_name"]),
            "segment": str(row["segment"]),
            "industry": str(row["industry"]),
            "region": str(row["region_name"]),
            "seats": round(float(row["seats"]), 1),
            "mrr": round(float(row["mrr"]), 2),
            "usage_per_seat": round(float(row["usage_per_seat"]), 2),
            "nps_score": round(float(row["nps_score"]), 1),
            "discount_pct": round(float(row["discount_pct"]), 4),
            "churn_probability": round(probability, 4),
            "risk_band": band,
            "actual_churn": int(row["is_churned"]),
            "cluster": int(row["cluster"]),
        })
    # * Sorted riskiest-first, so the table opens on the accounts that matter.
    customers.sort(key=lambda item: -item["churn_probability"])

    # --- Cluster summary -----------------------------------------------------
    cluster_summary = []
    for cluster_id, group in working.groupby("cluster"):
        cluster_summary.append({
            "cluster": int(cluster_id),
            "customers": int(len(group)),
            "churn_rate": round(float(group["is_churned"].mean()), 4),
            "mean_seats": round(float(group["seats"].mean()), 1),
            "mean_mrr": round(float(group["mrr"].mean()), 2),
            "mean_usage_per_seat": round(float(group["usage_per_seat"].mean()), 2),
            "mean_nps": round(float(group["nps_score"].mean()), 1),
            "dominant_segment": str(group["segment"].mode().iat[0]),
        })

    return {
        "monthly_revenue": [
            {"date_key": int(row["date_key"]), "month": str(row["month_name"]),
             "mrr": round(float(row["mrr"]), 2), "customers": int(row["customers"]),
             "arpa": float(row["arpa"])}
            for _, row in monthly.iterrows()
        ],
        "revenue_by_segment": revenue_by("segment"),
        "revenue_by_region": revenue_by("region_name"),
        "revenue_by_industry": revenue_by("industry"),
        "customers": customers,
        "cluster_summary": cluster_summary,
    }


