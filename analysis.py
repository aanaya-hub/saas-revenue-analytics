# 2. CLEAN — repair the eight deliberate defects
# ============================================================================

def clean(df):
    """Repair the defects and return (clean_df, list_of_repairs).

    Every repair is appended to a log as a dictionary with the same five keys, so
    the results file and the dashboard can render them uniformly:

        defect    what was wrong
        rows      how many rows it affected
        action    what we did about it
        why       the reasoning, in one sentence

    The returns are a tuple, not two separate calls, because the two are always
    wanted together: a cleaned table with no record of what was changed is worse
    than no cleaning at all.
    """
    repairs = []
    df = df.copy()   # never mutate the caller's DataFrame — see the note below

    # ! WHY .copy() FIRST
    # ! Without it, this function would edit the DataFrame the caller passed in.
    # ! Python passes objects by reference, so `df = df.dropna()` rebinds the
    # ! local name but `df["col"] = ...` changes the ORIGINAL object. A function
    # ! that silently edits its input is one of the hardest bugs to trace,
    # ! because the damage appears somewhere else entirely.

    # --- Defect 7: duplicated fact rows -------------------------------------
    # * The generator appends a second copy of 12 rows, imitating an import that
    # * ran twice. Duplicates double-count revenue, so they go first: every
    # * figure below would be wrong while they remain.
    before = len(df)
    df = df.drop_duplicates(subset=["fact_id"], keep="first").reset_index(drop=True)
    removed = before - len(df)
    repairs.append({
        "defect": "Duplicated fact rows",
        "rows": removed,
        "scope": "fact rows",
        "action": "Dropped, keeping the first occurrence of each fact_id",
        "why": "Duplicate rows double-count revenue and inflate every total",
    })

    # --- Defects 4 and 5: usage_events --------------------------------------
    # ! COUNT THE BLANKS FIRST, THEN OVERWRITE.
    # ! The order matters. If the negatives were turned into NaN before the
    # ! blanks were counted, the count would report 22 instead of 18 and the
    # ! repair log would quietly claim a defect is 22% larger than it is. The
    # ! log exists to be trustworthy, so it is built in the order the defects
    # ! actually occur: measure, then fix.
    blank_usage_count = int(df["usage_events"].isna().sum())

    # * A customer cannot use the product a negative number of times. These are
    # * impossible values rather than merely unusual ones, so they are treated
    # * as MISSING rather than kept — the same treatment blanks get.
    negative = df["usage_events"] < 0
    negative_count = int(negative.sum())
    df.loc[negative, "usage_events"] = np.nan

    # * Impute with the MEDIAN, not the mean. Usage is right-skewed — a few
    # * heavy users pull the mean upward — so the median describes the typical
    # * customer and is not distorted by the accounts that matter least to a
    # * "typical value" estimate.
    total_missing = blank_usage_count + negative_count
    median_usage = df["usage_events"].median()
    df["usage_events_filled"] = df["usage_events"].fillna(median_usage)

    repairs.append({
        "defect": "Blank usage_events",
        "rows": blank_usage_count,
        "scope": "fact rows",
        "action": f"Imputed with the median ({median_usage:.1f})",
        "why": "A blank is a missing observation; dropping the row would bias the mean",
    })
    repairs.append({
        "defect": "Negative usage_events",
        "rows": negative_count,
        "scope": "fact rows",
        "action": f"Set to missing, then imputed with the same median ({median_usage:.1f})",
        "why": "Impossible values are not observations and would drag any average down",
    })

    # --- Defect 6: discount above 100% --------------------------------------
    # * A discount of 1.3 means the customer is paid to use the product, and
    # * produces a negative invoice. The generator added exactly 1.0 to these
    # * values, so subtracting 1.0 RECOVERS the true discount rather than
    # * guessing at a replacement.
    over = df["discount_pct"] > 1.0
    df.loc[over, "discount_pct"] = df.loc[over, "discount_pct"] - 1.0
    repairs.append({
        "defect": "Discount above 100%",
        "rows": int(over.sum()),
        "scope": "fact rows",
        "action": "Subtracted 1.0, recovering the intended value",
        "why": "A discount over 100% produces negative revenue and breaks the invoice check",
    })

    # --- Defect 1: blank industry -------------------------------------------
    # * Filled with the literal text "Unknown" rather than a guess. Inventing an
    # * industry would put made-up information into a group-by: every figure
    # * broken down by industry would then contain numbers that are not real.
    # * "Unknown" keeps the row and states honestly what is not known.
    blank_industry = df["industry"].isna() | (df["industry"].astype(str).str.strip() == "")
    df.loc[blank_industry, "industry"] = "Unknown"
    # * Counted in CUSTOMERS, not fact rows. The defect was injected on
    # * dim_customer, so saying "22 rows" would be technically true of the
    # * joined table and misleading about the size of the problem: it is six
    # * customers, each appearing once per month.
    repairs.append({
        "defect": "Blank industry",
        "rows": int(df.loc[blank_industry, "customer_id"].nunique()),
        "scope": "customers",
        "action": 'Filled with the literal "Unknown"',
        "why": "Guessing an industry would invent data; naming it Unknown keeps the row honest",
    })

    # --- Defect 2: blank region_id (a broken foreign key) -------------------
    # * A missing region is worse than a missing label: the LEFT JOIN returns
    # * NULL, and any per-region total silently excludes these customers.
    # * The fix assigns the most common region, and says so. That is a judgement
    # * call, and the count is recorded so its effect can be measured.
    blank_region = df["region_name"].isna()
    if blank_region.any():
        modal_region = df["region_name"].mode().iat[0]
        df.loc[blank_region, "region_name"] = modal_region
        df.loc[blank_region, "country"] = "Unknown"
        action = f'Assigned the most common region ("{modal_region}")'
    else:
        action = "Nothing to fix"
    repairs.append({
        "defect": "Blank region_id (broken foreign key)",
        "rows": int(df.loc[blank_region, "customer_id"].nunique()),
        "scope": "customers",
        "action": action,
        "why": "A broken foreign key makes rows vanish from any per-region total",
    })

    # --- Defect 3: mixed date formats ---------------------------------------
    # * signup_date should be ISO (YYYY-MM-DD) but a few rows are DD/MM/YYYY.
    # * pandas cannot infer both from one column, so the two are parsed
    # * SEPARATELY with an explicit format for each, and then recombined. Asking
    # * pandas to guess would silently read "03/04/2024" as 3 April when it means
    # * 4 March — the classic date bug that produces plausible wrong answers.
    raw_dates = df["signup_date"].astype(str)
    iso_mask = raw_dates.str.match(r"^\d{4}-\d{2}-\d{2}$")
    slash_mask = raw_dates.str.match(r"^\d{2}/\d{2}/\d{4}$")

    parsed = pd.Series(pd.NaT, index=df.index, dtype="datetime64[ns]")
    parsed.loc[iso_mask] = pd.to_datetime(raw_dates[iso_mask], format="%Y-%m-%d", errors="coerce")
    parsed.loc[slash_mask] = pd.to_datetime(raw_dates[slash_mask], format="%d/%m/%Y", errors="coerce")
    df["signup_date_parsed"] = parsed
    repairs.append({
        "defect": "Mixed date formats (DD/MM/YYYY among ISO)",
        "rows": int(df.loc[slash_mask, "customer_id"].nunique()),
        "scope": "customers",
        "action": "Parsed each format explicitly, then recombined",
        "why": "Letting pandas guess can swap day and month, producing plausible wrong dates",
    })

    # --- Defect 8: rep hired after the customer signed up -------------------
    # * Logically impossible: nobody can own an account before they were hired.
    # * It cannot be repaired by guessing a better rep, so it is FLAGGED instead.
    # * Any analysis of rep performance must exclude these rows, and the flag is
    # * what makes that possible.
    rep_hire = pd.to_datetime(df["rep_id"].map(
        {rep["rep_id"]: rep["hire_date"] for rep in config.REPS}
    ))
    impossible = df["signup_date_parsed"] < rep_hire
    df["rep_assignment_valid"] = ~impossible
    repairs.append({
        "defect": "Rep hired after the customer signed up",
        "rows": int(df.loc[impossible, "customer_id"].nunique()),
        "scope": "customers",
        "action": "Flagged in rep_assignment_valid, not corrected",
        "why": "There is no correct rep to assign; the honest fix is to mark it and exclude it",
    })

    # --- Derived columns ----------------------------------------------------
    # * Now that usage is trustworthy, derive the per-seat figure. It is a
    # * DERIVED measure and is not stored in the database, so there is exactly
    # * one definition of it rather than two that can drift apart.
    # *
    # * .clip(lower=1) guards the division: if any seat count were ever 0 this
    # * would divide by zero and produce infinity, which then poisons every
    # * average downstream. Clipping to a minimum of 1 makes that impossible.
    df["usage_per_seat"] = df["usage_events_filled"] / df["seats"].clip(lower=1)

    # * The churn label. Derived from the panel structure, never read from a
    # * stored column: a churned customer's last observed month comes before the
    # * final month in the window.
    final_month = df["date_key"].max()
    last_seen = df.groupby("customer_id")["date_key"].max()
    df["is_churned"] = df["customer_id"].map(last_seen).lt(final_month).astype(int)

    return df, repairs


